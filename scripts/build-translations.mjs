import fs from "node:fs";
const source = fs
  .readFileSync("src/locales/interface.tsv", "utf8")
  .replace(/^\uFEFF/, "")
  .trimEnd();
const [header, ...lines] = source.split(/\r?\n/);
const languages = header.split("\t").slice(1);
const result = Object.fromEntries(
  ["en", ...languages].map((language) => [language, {}]),
);
const seen = new Set();
for (const [index, line] of lines.entries()) {
  const cells = line.split("\t");
  if (
    cells.length !== languages.length + 1 ||
    cells.some((cell) => !cell.trim())
  )
    throw new Error(
      `Invalid translation row ${index + 2}: expected ${languages.length + 1} nonempty cells, found ${cells.length}`,
    );
  const [key, ...values] = cells;
  if (seen.has(key)) throw new Error(`Duplicate translation key: ${key}`);
  seen.add(key);
  result.en[key] = key;
  languages.forEach((language, offset) => {
    result[language][key] = values[offset];
  });
}
fs.writeFileSync(
  "src/locales/translations.ts",
  "// Generated by scripts/build-translations.mjs from interface.tsv.\nexport const interfaceTranslations: Record<string, Record<string,string>> = " +
    JSON.stringify(result, null, 2) +
    ";\n",
);
console.log(
  `Validated ${seen.size} translation entries in ${languages.length} languages.`,
);
